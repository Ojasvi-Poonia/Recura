"""Export what the agent learned on the benchmark as capped priors for previews.

Runs the same configuration as `make eval`, takes the posteriors the agent ends with,
and writes them to config/benchmark_priors.json after shrinking (src/decide/priors.py
explains the shrinkage and why previews need it).

This never feeds back into the benchmark: `make eval` builds its model with no priors,
and tests/test_priors.py asserts that.

    make priors
"""

from __future__ import annotations

import json

from eval.run_batch import RUN_SEED, RunConfig, run
from src.decide.priors import MIN_EVIDENCE, PRIOR_STRENGTH, PRIORS_PATH, shrink_snapshot


def build(cohort=None, latents=None) -> dict:
    _, agent = run(RunConfig(), quiet=True, cohort=cohort, latents=latents)
    return {
        "about": "Capped priors for previews (audit, import, shadow mode). Learned on the "
                 "frozen SYNTHETIC cohort, not on any real merchant. Generated by "
                 "`make priors`; do not edit by hand.",
        "run_seed": RUN_SEED,
        "prior_strength": PRIOR_STRENGTH,
        "min_evidence": MIN_EVIDENCE,
        "cells": shrink_snapshot(agent.model.snapshot()),
    }


def main() -> None:
    payload = build()
    PRIORS_PATH.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n",
                           encoding="utf-8")
    kept = sum(1 for c in payload["cells"].values() if c["basis"] == "benchmark")
    print(f"wrote {PRIORS_PATH}: {len(payload['cells'])} cells, {kept} with benchmark "
          f"evidence, strength capped at {PRIOR_STRENGTH:g}")


if __name__ == "__main__":
    main()
