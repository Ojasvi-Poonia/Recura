"""Benchmark priors: what a preview believes before it has seen a merchant's outcomes.

`make eval` starts every cell at Beta(1, 1) and that must not change: seeding the
benchmark run with anything else would be peeking (see the note in bandit.py). But the
same flat prior is useless for showing a merchant what the agent would do with THEIR
export. With every cell at 0.5 no action beats doing nothing, and a Thompson draw from
it is noise - the audit report was printing whichever action the random generator
happened to favour, and printed a different one when the file's rows were reordered.

So previews (`make audit`, `make import DECIDE=1`, shadow mode) start from what the
agent learned on the frozen synthetic cohort, shrunk hard:

  - STRENGTH IS CAPPED. A cell the benchmark observed 2,833 times enters as if it had
    been observed 20 times. It is a starting point a merchant's own outcomes overrule
    within weeks, not a conclusion.
  - NO EVIDENCE MEANS NO PROPOSAL. A cell the benchmark barely tried keeps a posterior
    near 0.5, which would make untested actions look better than everything measured.
    Those cells are set to the same class's do-nothing rate, so their increment over
    doing nothing is zero and a preview never proposes an action nothing supports.

WHAT THESE NUMBERS ARE NOT
They come from a simulator calibrated to published sources (eval/CALIBRATION.md), not
from any real merchant. Every surface that uses them says so next to the output.

The file is generated by `make priors` and committed; a test fails if it drifts from
what the benchmark run actually learns.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from src.decide.bandit import BetaPosterior, PropensityModel
from src.models import ActionType, FailureClass

PRIORS_PATH = Path(__file__).resolve().parents[2] / "config" / "benchmark_priors.json"

# Pseudo-observations a benchmark cell may carry into a preview. Twenty is roughly one
# working day of failures for a small merchant: enough to rank actions, small enough
# that real outcomes dominate almost immediately.
PRIOR_STRENGTH = 20.0
# Below this many benchmark observations a cell's mean is still mostly the flat prior.
MIN_EVIDENCE = 5
# Beta parameters must stay positive, so a cell that never once recovered is not zero.
MEAN_FLOOR = 0.01

BASIS_BENCHMARK = "benchmark"
BASIS_NO_EVIDENCE = "no_evidence_baseline"


class PriorsUnavailable(Exception):
    """The committed priors file is missing or unreadable."""


def _key(failure_class: FailureClass, action: ActionType) -> str:
    return f"{failure_class.value}|{action.value}"


def shrink_snapshot(snapshot: dict[str, dict[str, float]]) -> dict[str, dict]:
    """Turn a learned posterior snapshot into capped priors, one per cell.

    `snapshot` is `PropensityModel.snapshot()`: {"CLASS|ACTION": {alpha, beta, mean, n}}.
    """
    cells: dict[str, dict] = {}
    for failure_class in FailureClass:
        baseline = snapshot.get(_key(failure_class, ActionType.NO_ACTION))
        baseline_mean = baseline["mean"] if baseline else 0.5
        for action in ActionType:
            learned = snapshot.get(_key(failure_class, action))
            observed = learned["n"] if learned else 0
            if learned and observed >= MIN_EVIDENCE:
                mean, basis = learned["mean"], BASIS_BENCHMARK
                strength = min(learned["alpha"] + learned["beta"], PRIOR_STRENGTH)
            else:
                mean, basis = baseline_mean, BASIS_NO_EVIDENCE
                strength = min(float(MIN_EVIDENCE), PRIOR_STRENGTH)
            mean = min(max(mean, MEAN_FLOOR), 1.0 - MEAN_FLOOR)
            cells[_key(failure_class, action)] = {
                "alpha": round(mean * strength, 4),
                "beta": round((1.0 - mean) * strength, 4),
                "basis": basis,
                "benchmark_n": int(observed),
            }
    return cells


def model_from_cells(cells: dict[str, dict]) -> PropensityModel:
    model = PropensityModel()
    for key, cell in cells.items():
        class_name, _, action_name = key.partition("|")
        model.seed(FailureClass(class_name), ActionType(action_name),
                   BetaPosterior(float(cell["alpha"]), float(cell["beta"])))
    return model


@lru_cache(maxsize=1)
def _committed_cells(path: str) -> dict[str, dict]:
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))["cells"]
    except (OSError, ValueError, KeyError) as exc:
        raise PriorsUnavailable(
            f"could not read benchmark priors at {path}: {exc}. "
            "Regenerate them with `make priors`.") from exc


def load_benchmark_priors(path: Path | None = None) -> PropensityModel:
    """A fresh model seeded from the committed priors. Each caller gets its own copy."""
    return model_from_cells(_committed_cells(str(path or PRIORS_PATH)))
